-- Cities the owner manages. A City ride is only offered inside one, and later work keys driver
-- locations and batch matching by city. Nothing is seeded: the owner draws the map.
CREATE TABLE public.cities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(80) NOT NULL UNIQUE,
    center_lat double precision NOT NULL,
    center_lon double precision NOT NULL,
    radius_km double precision NOT NULL CHECK (radius_km BETWEEN 1 AND 100),
    active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT now()
);

-- Null for every Trip and for City rides booked before cities existed.
ALTER TABLE public.travel_bookings
    ADD COLUMN city_id bigint REFERENCES public.cities(id);
