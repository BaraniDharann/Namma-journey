-- Bus booking (docs/superpowers/specs/2026-11-04-bus-booking-design.md): travels owners list buses
-- with a seat layout, run them on routes with boarding and dropping points, and customers book
-- single seats for any part of a route. The whole data model is here, including tickets, payments,
-- payouts and reviews, which the later parts of the module use.
--
-- Every bus table except bus_places carries owner_id and gets the V28 row-level security policies,
-- so an owner's request sees only their own rows. Customer, admin and job connections are unscoped.

-- The seat exclusion constraint compares bigint and text columns with = inside a GiST index.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- What an owner runs (the owner menu shows car items, bus items or both), and the platform's cut of
-- their bus fares, which the admin can change per owner.
ALTER TABLE public.owners
    ADD COLUMN fleet_type character varying(6) NOT NULL DEFAULT 'CARS'
        CONSTRAINT owners_fleet_type_check CHECK (fleet_type IN ('CARS', 'BUSES', 'BOTH')),
    ADD COLUMN bus_commission_percent numeric(5, 2) NOT NULL DEFAULT 8
        CONSTRAINT owners_bus_commission_check CHECK (bus_commission_percent BETWEEN 0 AND 50);

-- Towns a route can stop at. Shared by every owner (no owner_id, no row-level security); owners can
-- add a town that is missing.
CREATE TABLE public.bus_places (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(80) NOT NULL,
    district character varying(80),
    lat double precision,
    lng double precision,
    created_by_owner_id bigint REFERENCES public.owners (id),
    created_at timestamp(6) without time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_bus_places_name ON public.bus_places (lower(name));

-- ---------------------------------------------------------------------------------------------
-- Buses and their seat layouts
-- ---------------------------------------------------------------------------------------------

CREATE TABLE public.buses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    registration_number character varying(20) NOT NULL,
    name character varying(80) NOT NULL,
    ac boolean NOT NULL DEFAULT true,
    permit_type character varying(20) NOT NULL
        CONSTRAINT buses_permit_type_check CHECK (permit_type IN ('STAGE_CARRIAGE', 'CONTRACT_CARRIAGE', 'ALL_INDIA_TOURIST')),
    -- Comma-separated, e.g. "Water bottle,Charging point,Blanket".
    amenities character varying(500),
    status character varying(10) NOT NULL DEFAULT 'DRAFT'
        CONSTRAINT buses_status_check CHECK (status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED')),
    rejection_reason character varying(500),
    submitted_at timestamp(6) without time zone,
    reviewed_at timestamp(6) without time zone,
    reviewed_by_admin_id bigint,
    created_at timestamp(6) without time zone NOT NULL DEFAULT now()
);
-- Same key as the cars' plate index (V27): upper case, no spaces.
CREATE UNIQUE INDEX uq_buses_registration ON public.buses (upper(replace(registration_number, ' ', '')));
CREATE INDEX idx_buses_owner ON public.buses (owner_id);
CREATE INDEX idx_buses_status ON public.buses (status);

-- One of each document per bus; uploading again replaces it.
CREATE TABLE public.bus_documents (
    bus_id bigint NOT NULL REFERENCES public.buses (id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    type character varying(10) NOT NULL
        CONSTRAINT bus_documents_type_check CHECK (type IN ('RC', 'PERMIT', 'INSURANCE', 'FITNESS')),
    path character varying(1000) NOT NULL,
    expires_on date NOT NULL,
    uploaded_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (bus_id, type)
);

CREATE TABLE public.bus_photos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id bigint NOT NULL REFERENCES public.buses (id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    path character varying(1000) NOT NULL,
    position integer NOT NULL DEFAULT 0
);
CREATE INDEX idx_bus_photos_bus ON public.bus_photos (bus_id, position);

-- Deck 0 is the lower deck, 1 the upper. A seater has no berth; a sleeper is a SINGLE or DOUBLE
-- berth. pair_label is the seat next to this one (for the gender rule), kept symmetric by the app.
CREATE TABLE public.bus_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id bigint NOT NULL REFERENCES public.buses (id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    label character varying(8) NOT NULL,
    deck integer NOT NULL CONSTRAINT bus_seats_deck_check CHECK (deck IN (0, 1)),
    row_no integer NOT NULL CONSTRAINT bus_seats_row_check CHECK (row_no >= 0),
    col_no integer NOT NULL CONSTRAINT bus_seats_col_check CHECK (col_no >= 0),
    kind character varying(7) NOT NULL CONSTRAINT bus_seats_kind_check CHECK (kind IN ('SEATER', 'SLEEPER')),
    berth character varying(6) CONSTRAINT bus_seats_berth_check CHECK (berth IN ('SINGLE', 'DOUBLE')),
    pair_label character varying(8),
    ladies_only boolean NOT NULL DEFAULT false,
    CONSTRAINT bus_seats_kind_berth_check CHECK ((kind = 'SEATER') = (berth IS NULL)),
    CONSTRAINT uq_bus_seats_label UNIQUE (bus_id, label),
    CONSTRAINT uq_bus_seats_position UNIQUE (bus_id, deck, row_no, col_no)
);

-- ---------------------------------------------------------------------------------------------
-- Routes: ordered stops, boarding/dropping points at each stop, fares per stop pair and seat class
-- ---------------------------------------------------------------------------------------------

-- run_days: bit 0 = Monday ... bit 6 = Sunday. cancellation_policy: slabs ordered by minHours
-- descending, e.g. [{"minHours":48,"percent":10},...,{"minHours":0,"percent":100}].
CREATE TABLE public.bus_routes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    bus_id bigint NOT NULL REFERENCES public.buses (id),
    name character varying(120) NOT NULL,
    run_days smallint NOT NULL CONSTRAINT bus_routes_run_days_check CHECK (run_days BETWEEN 1 AND 127),
    active_from date NOT NULL,
    active_to date,
    max_seats_per_booking integer NOT NULL DEFAULT 6
        CONSTRAINT bus_routes_max_seats_check CHECK (max_seats_per_booking BETWEEN 1 AND 10),
    cancellation_policy jsonb NOT NULL,
    status character varying(10) NOT NULL DEFAULT 'DRAFT'
        CONSTRAINT bus_routes_status_check CHECK (status IN ('DRAFT', 'PUBLISHED', 'PAUSED')),
    created_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT bus_routes_dates_check CHECK (active_to IS NULL OR active_to >= active_from)
);
CREATE INDEX idx_bus_routes_owner ON public.bus_routes (owner_id);
CREATE INDEX idx_bus_routes_bus ON public.bus_routes (bus_id);

CREATE TABLE public.bus_route_stops (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id bigint NOT NULL REFERENCES public.bus_routes (id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    seq integer NOT NULL CONSTRAINT bus_route_stops_seq_check CHECK (seq >= 0),
    place_id bigint NOT NULL REFERENCES public.bus_places (id),
    CONSTRAINT uq_bus_route_stops_seq UNIQUE (route_id, seq),
    CONSTRAINT uq_bus_route_stops_place UNIQUE (route_id, place_id)
);
CREATE INDEX idx_bus_route_stops_place ON public.bus_route_stops (place_id);

-- A point's actual time on a trip is travel_date + day_offset days + time.
CREATE TABLE public.bus_route_points (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id bigint NOT NULL REFERENCES public.bus_route_stops (id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    kind character varying(8) NOT NULL
        CONSTRAINT bus_route_points_kind_check CHECK (kind IN ('BOARDING', 'DROPPING', 'BOTH')),
    name character varying(120) NOT NULL,
    address character varying(300),
    landmark character varying(150),
    lat double precision,
    lng double precision,
    day_offset integer NOT NULL DEFAULT 0 CONSTRAINT bus_route_points_day_offset_check CHECK (day_offset BETWEEN 0 AND 3),
    time time without time zone NOT NULL
);
CREATE INDEX idx_bus_route_points_stop ON public.bus_route_points (stop_id);

-- Fares are entered without GST. Seat class: SEATER, LOWER_SINGLE, LOWER_DOUBLE, UPPER_SINGLE, UPPER_DOUBLE.
CREATE TABLE public.bus_route_fares (
    route_id bigint NOT NULL REFERENCES public.bus_routes (id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    from_seq integer NOT NULL,
    to_seq integer NOT NULL,
    seat_class character varying(14) NOT NULL
        CONSTRAINT bus_route_fares_class_check CHECK (seat_class IN ('SEATER', 'LOWER_SINGLE', 'LOWER_DOUBLE', 'UPPER_SINGLE', 'UPPER_DOUBLE')),
    fare numeric(10, 2) NOT NULL CONSTRAINT bus_route_fares_fare_check CHECK (fare > 0),
    PRIMARY KEY (route_id, from_seq, to_seq, seat_class),
    CONSTRAINT bus_route_fares_seq_check CHECK (from_seq >= 0 AND from_seq < to_seq)
);

-- ---------------------------------------------------------------------------------------------
-- Trips (one per route per date) and the seats sold on them
-- ---------------------------------------------------------------------------------------------

CREATE TABLE public.bus_trips (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id bigint NOT NULL REFERENCES public.bus_routes (id),
    bus_id bigint NOT NULL REFERENCES public.buses (id),
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    travel_date date NOT NULL,
    departure_at timestamp(6) without time zone NOT NULL,
    arrival_at timestamp(6) without time zone NOT NULL,
    status character varying(10) NOT NULL DEFAULT 'SCHEDULED'
        CONSTRAINT bus_trips_status_check CHECK (status IN ('SCHEDULED', 'DEPARTED', 'COMPLETED', 'CANCELLED')),
    cancel_reason character varying(500),
    driver_name character varying(80),
    driver_phone character varying(15),
    conductor_name character varying(80),
    conductor_phone character varying(15),
    reminder_sent_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    -- Trip creation runs on publish and every night; this makes running it twice harmless.
    CONSTRAINT uq_bus_trips_route_date UNIQUE (route_id, travel_date)
);
CREATE INDEX idx_bus_trips_owner_date ON public.bus_trips (owner_id, travel_date);
CREATE INDEX idx_bus_trips_status_departure ON public.bus_trips (status, departure_at);
CREATE INDEX idx_bus_trips_date ON public.bus_trips (travel_date);

-- A booking for a stretch of the route: one passenger's whole journey on a ticket.
CREATE TABLE public.bus_tickets (
    id uuid PRIMARY KEY,
    ticket_no character varying(12) NOT NULL CONSTRAINT uq_bus_tickets_ticket_no UNIQUE,
    user_id uuid NOT NULL REFERENCES public.users (id),
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    trip_id bigint NOT NULL REFERENCES public.bus_trips (id),
    from_seq integer NOT NULL,
    to_seq integer NOT NULL,
    boarding_point_id bigint NOT NULL REFERENCES public.bus_route_points (id),
    dropping_point_id bigint NOT NULL REFERENCES public.bus_route_points (id),
    contact_phone character varying(15) NOT NULL,
    contact_email character varying(255),
    extra_phone character varying(15),
    fare_total numeric(10, 2) NOT NULL,
    gst_percent numeric(5, 2) NOT NULL,
    gst_total numeric(10, 2) NOT NULL,
    total_amount numeric(10, 2) NOT NULL,
    commission_percent numeric(5, 2) NOT NULL,
    -- The route's slabs when the ticket was bought; later edits by the owner do not change it.
    cancellation_policy jsonb NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'PENDING'
        CONSTRAINT bus_tickets_status_check CHECK (status IN ('PENDING', 'CONFIRMED', 'PARTIALLY_CANCELLED', 'CANCELLED',
                                                              'SERVICE_CANCELLED', 'EXPIRED', 'COMPLETED')),
    hold_expires_at timestamp(6) without time zone,
    idempotency_key character varying(100),
    created_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    confirmed_at timestamp(6) without time zone,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT bus_tickets_seq_check CHECK (from_seq >= 0 AND from_seq < to_seq),
    CONSTRAINT uq_bus_tickets_idempotency UNIQUE (user_id, idempotency_key)
);
CREATE INDEX idx_bus_tickets_user ON public.bus_tickets (user_id, created_at DESC);
CREATE INDEX idx_bus_tickets_trip ON public.bus_tickets (trip_id);
CREATE INDEX idx_bus_tickets_owner ON public.bus_tickets (owner_id);
CREATE INDEX idx_bus_tickets_pending ON public.bus_tickets (hold_expires_at) WHERE status = 'PENDING';

-- legs covers stops from_seq up to (not including) to_seq: a seat sold Chennai(0)→Trichy(2) is
-- taken for legs 0 and 1 only, so Trichy(2)→Madurai(3) can still be sold. Computed by Postgres from
-- from_seq/to_seq, so the app never writes a range.
CREATE TABLE public.bus_seat_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id bigint NOT NULL REFERENCES public.bus_trips (id),
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    seat_label character varying(8) NOT NULL,
    from_seq integer NOT NULL,
    to_seq integer NOT NULL,
    legs int4range GENERATED ALWAYS AS (int4range(from_seq, to_seq)) STORED,
    status character varying(10) NOT NULL
        CONSTRAINT bus_seat_allocations_status_check CHECK (status IN ('HELD', 'CONFIRMED', 'BLOCKED', 'CANCELLED', 'EXPIRED')),
    gender character varying(1) CONSTRAINT bus_seat_allocations_gender_check CHECK (gender IN ('M', 'F')),
    ticket_id uuid REFERENCES public.bus_tickets (id),
    expires_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT bus_seat_allocations_seq_check CHECK (from_seq >= 0 AND from_seq < to_seq),
    -- No seat is ever sold twice for the same stretch: two live allocations of one seat on one trip
    -- may not share a leg. Adjacent stretches ([0,1) and [1,2)) do not overlap. Expired and
    -- cancelled rows are ignored, so flipping a stale hold to EXPIRED frees the seat.
    CONSTRAINT no_seat_overlap EXCLUDE USING gist (trip_id WITH =, seat_label WITH =, legs WITH &&)
        WHERE (status IN ('HELD', 'CONFIRMED', 'BLOCKED'))
);
CREATE INDEX idx_bus_seat_allocations_ticket ON public.bus_seat_allocations (ticket_id);
CREATE INDEX idx_bus_seat_allocations_held ON public.bus_seat_allocations (expires_at) WHERE status = 'HELD';

CREATE TABLE public.bus_ticket_passengers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id uuid NOT NULL REFERENCES public.bus_tickets (id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    seat_label character varying(8) NOT NULL,
    seat_class character varying(14) NOT NULL
        CONSTRAINT bus_ticket_passengers_class_check CHECK (seat_class IN ('SEATER', 'LOWER_SINGLE', 'LOWER_DOUBLE', 'UPPER_SINGLE', 'UPPER_DOUBLE')),
    name character varying(80) NOT NULL,
    age integer NOT NULL CONSTRAINT bus_ticket_passengers_age_check CHECK (age BETWEEN 0 AND 120),
    gender character varying(1) NOT NULL CONSTRAINT bus_ticket_passengers_gender_check CHECK (gender IN ('M', 'F')),
    fare numeric(10, 2) NOT NULL,
    gst numeric(10, 2) NOT NULL,
    status character varying(10) NOT NULL DEFAULT 'CONFIRMED'
        CONSTRAINT bus_ticket_passengers_status_check CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    cancel_charge numeric(10, 2),
    refund_amount numeric(10, 2),
    cancelled_at timestamp(6) without time zone
);
CREATE INDEX idx_bus_ticket_passengers_ticket ON public.bus_ticket_passengers (ticket_id);

-- ---------------------------------------------------------------------------------------------
-- Money: payments and refunds (separate from the car `payments` table, which needs a car booking
-- and holds a single refund), owner payouts per completed trip
-- ---------------------------------------------------------------------------------------------

CREATE TABLE public.bus_payments (
    id uuid PRIMARY KEY,
    ticket_id uuid NOT NULL REFERENCES public.bus_tickets (id),
    user_id uuid NOT NULL,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    amount numeric(10, 2) NOT NULL CONSTRAINT bus_payments_amount_check CHECK (amount > 0),
    status character varying(10) NOT NULL DEFAULT 'CREATED'
        CONSTRAINT bus_payments_status_check CHECK (status IN ('CREATED', 'CAPTURED', 'FAILED')),
    razorpay_order_id character varying(64) CONSTRAINT uq_bus_payments_order UNIQUE,
    razorpay_payment_id character varying(64) CONSTRAINT uq_bus_payments_payment UNIQUE,
    created_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    captured_at timestamp(6) without time zone
);
CREATE INDEX idx_bus_payments_ticket ON public.bus_payments (ticket_id);

CREATE TABLE public.bus_refunds (
    id uuid PRIMARY KEY,
    ticket_id uuid NOT NULL REFERENCES public.bus_tickets (id),
    payment_id uuid NOT NULL REFERENCES public.bus_payments (id),
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    amount numeric(10, 2) NOT NULL CONSTRAINT bus_refunds_amount_check CHECK (amount > 0),
    reason character varying(300),
    status character varying(10) NOT NULL DEFAULT 'PENDING'
        CONSTRAINT bus_refunds_status_check CHECK (status IN ('PENDING', 'PROCESSED', 'FAILED')),
    razorpay_refund_id character varying(64),
    created_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    processed_at timestamp(6) without time zone
);
CREATE INDEX idx_bus_refunds_ticket ON public.bus_refunds (ticket_id);
CREATE INDEX idx_bus_refunds_pending ON public.bus_refunds (created_at) WHERE status = 'PENDING';

-- One payout per completed trip: gross = fares travelled + cancellation charges kept; the platform
-- keeps commission_percent of it.
CREATE TABLE public.bus_owner_payouts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    trip_id bigint NOT NULL REFERENCES public.bus_trips (id) CONSTRAINT uq_bus_owner_payouts_trip UNIQUE,
    fares_travelled numeric(12, 2) NOT NULL,
    charges_kept numeric(12, 2) NOT NULL,
    gross numeric(12, 2) NOT NULL,
    commission_percent numeric(5, 2) NOT NULL,
    commission numeric(12, 2) NOT NULL,
    net numeric(12, 2) NOT NULL,
    status character varying(4) NOT NULL DEFAULT 'DUE' CONSTRAINT bus_owner_payouts_status_check CHECK (status IN ('DUE', 'PAID')),
    utr character varying(40),
    paid_at timestamp(6) without time zone,
    paid_by_admin_id bigint,
    created_at timestamp(6) without time zone NOT NULL DEFAULT now()
);
CREATE INDEX idx_bus_owner_payouts_owner ON public.bus_owner_payouts (owner_id, created_at DESC);
CREATE INDEX idx_bus_owner_payouts_status ON public.bus_owner_payouts (status);

CREATE TABLE public.bus_reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id uuid NOT NULL REFERENCES public.bus_tickets (id) CONSTRAINT uq_bus_reviews_ticket UNIQUE,
    bus_id bigint NOT NULL REFERENCES public.buses (id),
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    user_id uuid NOT NULL,
    rating integer NOT NULL CONSTRAINT bus_reviews_rating_check CHECK (rating BETWEEN 1 AND 5),
    comment character varying(1000),
    created_at timestamp(6) without time zone NOT NULL DEFAULT now()
);
CREATE INDEX idx_bus_reviews_bus ON public.bus_reviews (bus_id);

-- ---------------------------------------------------------------------------------------------
-- Row-level security, as V28: an owner's request sees only rows with their owner_id
-- ---------------------------------------------------------------------------------------------

-- V28's default privileges already cover tables created by the same login; granted again here in
-- case this migration runs as a different one.
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO nj_owner_scope;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO nj_owner_scope;

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['buses', 'bus_documents', 'bus_photos', 'bus_seats', 'bus_routes', 'bus_route_stops',
                             'bus_route_points', 'bus_route_fares', 'bus_trips', 'bus_seat_allocations', 'bus_tickets',
                             'bus_ticket_passengers', 'bus_payments', 'bus_refunds', 'bus_owner_payouts',
                             'bus_reviews'] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format('CREATE POLICY app_unscoped ON public.%I USING (current_user <> ''nj_owner_scope'') '
                       || 'WITH CHECK (current_user <> ''nj_owner_scope'')', t);
        EXECUTE format('CREATE POLICY owner_scoped ON public.%I TO nj_owner_scope '
                       || 'USING (public.nj_owner_visible(owner_id)) WITH CHECK (public.nj_owner_visible(owner_id))', t);
    END LOOP;
END $$;

