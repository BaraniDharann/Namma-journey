-- Many travels owners instead of one, verified by a NammaJourney admin.
--
-- The one existing owner becomes owner NJO-0001, already approved. Owners added from now on
-- start as PENDING_REVIEW applications with no password: an admin approves them, which assigns
-- the next Owner ID and emails a one-time password.

CREATE TABLE public.admins (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email character varying(255) NOT NULL,
    password character varying(255) NOT NULL,
    token_version bigint NOT NULL DEFAULT 0,
    created_at timestamp(6) without time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX admins_email_lower_key ON public.admins (lower(email));

ALTER TABLE public.owners
    ADD COLUMN owner_code character varying(20),
    -- APPROVED only while backfilling the existing owner; the default changes below.
    ADD COLUMN status character varying(20) NOT NULL DEFAULT 'APPROVED',
    ADD COLUMN travels_name character varying(255),
    ADD COLUMN contact_name character varying(255),
    ADD COLUMN phone character varying(20),
    ADD COLUMN pan_number text,                -- encrypted (FieldEncryption)
    ADD COLUMN pan_hash character varying(64), -- SHA-256 of the normalised PAN, for duplicates
    ADD COLUMN aadhaar_last4 character varying(4),
    ADD COLUMN aadhaar_consent_at timestamp(6) without time zone,
    ADD COLUMN registration_doc_path character varying(512),
    ADD COLUMN pan_doc_path character varying(512),
    ADD COLUMN aadhaar_doc_path character varying(512),
    ADD COLUMN bank_account_holder character varying(255),
    ADD COLUMN bank_account_number text,       -- encrypted
    ADD COLUMN bank_ifsc character varying(11),
    ADD COLUMN bank_name character varying(255),
    ADD COLUMN upi_id text,                    -- encrypted
    ADD COLUMN rejection_reason character varying(500),
    ADD COLUMN submitted_at timestamp(6) without time zone,
    ADD COLUMN reviewed_at timestamp(6) without time zone,
    ADD COLUMN reviewed_by_admin_id bigint REFERENCES public.admins (id),
    ADD COLUMN admin_reminded_at timestamp(6) without time zone,
    ADD COLUMN must_change_password boolean NOT NULL DEFAULT false,
    ADD COLUMN resubmit_token_hash character varying(64),
    ADD COLUMN resubmit_token_expires_at timestamp(6) without time zone,
    ADD COLUMN version bigint NOT NULL DEFAULT 0;

UPDATE public.owners SET owner_code = 'NJO-0001' WHERE id = (SELECT min(id) FROM public.owners);
UPDATE public.owners SET owner_code = 'NJO-' || lpad(id::text, 4, '0') WHERE owner_code IS NULL;

ALTER TABLE public.owners ALTER COLUMN status SET DEFAULT 'PENDING_REVIEW';
ALTER TABLE public.owners ALTER COLUMN password DROP NOT NULL;

CREATE SEQUENCE public.owner_code_seq START 2;

CREATE UNIQUE INDEX owners_owner_code_key ON public.owners (owner_code);
CREATE UNIQUE INDEX owners_pan_hash_key ON public.owners (pan_hash);
CREATE UNIQUE INDEX owners_email_lower_key ON public.owners (lower(email));
CREATE INDEX owners_status_submitted_idx ON public.owners (status, submitted_at);
CREATE UNIQUE INDEX owners_resubmit_token_key ON public.owners (resubmit_token_hash);

CREATE TABLE public.owner_cities (
    owner_id bigint NOT NULL REFERENCES public.owners (id) ON DELETE CASCADE,
    city_id bigint NOT NULL REFERENCES public.cities (id),
    PRIMARY KEY (owner_id, city_id)
);

-- What the admin checked by hand on a free official source, and who checked it.
CREATE TABLE public.owner_verification_checks (
    owner_id bigint NOT NULL REFERENCES public.owners (id) ON DELETE CASCADE,
    check_type character varying(30) NOT NULL,
    result character varying(20) NOT NULL,
    note character varying(500),
    checked_by_admin_id bigint NOT NULL REFERENCES public.admins (id),
    checked_at timestamp(6) without time zone NOT NULL,
    PRIMARY KEY (owner_id, check_type)
);

-- The UIDAI Secure QR read off the owner's Aadhaar upload (AadhaarQrVerifier). Only the last 4
-- digits of the number are ever in a QR, so the full number is not here either.
CREATE TABLE public.owner_aadhaar_qr (
    owner_id bigint PRIMARY KEY REFERENCES public.owners (id) ON DELETE CASCADE,
    status character varying(30) NOT NULL,
    name character varying(255),
    dob character varying(20),
    gender character varying(10),
    state character varying(100),
    pincode character varying(10),
    last4 character varying(4),
    photo_jpeg bytea,
    checked_at timestamp(6) without time zone NOT NULL
);
