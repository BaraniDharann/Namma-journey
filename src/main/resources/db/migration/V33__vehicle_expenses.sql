-- What an owner spends running a car or a bus: fuel, tolls, driver pay, maintenance, permits and
-- tax. Revenue minus these is the profit the owner's dashboards show, per vehicle and per period.
-- A bus expense may name the trip it was for (fuel and toll for one run); general costs such as
-- maintenance stay on the bus alone.

CREATE TABLE public.vehicle_expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    vehicle_kind character varying(3) NOT NULL
        CONSTRAINT vehicle_expenses_kind_check CHECK (vehicle_kind IN ('CAR', 'BUS')),
    vehicle_id bigint NOT NULL,
    bus_trip_id bigint REFERENCES public.bus_trips (id) ON DELETE SET NULL,
    spent_on date NOT NULL,
    category character varying(12) NOT NULL
        CONSTRAINT vehicle_expenses_category_check
        CHECK (category IN ('FUEL', 'TOLL', 'DRIVER_PAY', 'MAINTENANCE', 'PERMIT_TAX', 'OTHER')),
    amount numeric(10, 2) NOT NULL CONSTRAINT vehicle_expenses_amount_check CHECK (amount > 0),
    note character varying(200),
    created_at timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_vehicle_expenses_owner_day ON public.vehicle_expenses (owner_id, spent_on);
CREATE INDEX idx_vehicle_expenses_vehicle ON public.vehicle_expenses (vehicle_kind, vehicle_id, spent_on);
CREATE INDEX idx_vehicle_expenses_trip ON public.vehicle_expenses (bus_trip_id) WHERE bus_trip_id IS NOT NULL;

-- Row-level security, as V28: an owner's request sees only rows with their owner_id.
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO nj_owner_scope;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO nj_owner_scope;

ALTER TABLE public.vehicle_expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vehicle_expenses FORCE ROW LEVEL SECURITY;
CREATE POLICY app_unscoped ON public.vehicle_expenses
    USING (current_user <> 'nj_owner_scope') WITH CHECK (current_user <> 'nj_owner_scope');
CREATE POLICY owner_scoped ON public.vehicle_expenses TO nj_owner_scope
    USING (public.nj_owner_visible(owner_id)) WITH CHECK (public.nj_owner_visible(owner_id));
