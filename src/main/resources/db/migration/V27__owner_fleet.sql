-- A fleet driver always has an owner and an independent one never does. A database with fleet
-- drivers but no NJO-0001 fails here, loudly, rather than guessing an owner.
ALTER TABLE public.drivers
    ADD CONSTRAINT drivers_owner_fleet_has_owner CHECK ((fleet = 'OWNER_FLEET') = (owner_id IS NOT NULL)),
    ADD CONSTRAINT drivers_fleet_no_city CHECK (NOT serves_city OR fleet = 'INDEPENDENT');

ALTER TABLE public.travel_packages ALTER COLUMN owner_id SET NOT NULL;

-- One car cannot be on two active trips on overlapping dates (same shape as no_driver_overlap, V13).
ALTER TABLE public.travel_bookings
    ADD CONSTRAINT no_vehicle_overlap
    EXCLUDE USING gist (
        vehicle_id WITH =,
        daterange(from_date, to_date, '[]') WITH &&
    )
    WHERE (vehicle_id IS NOT NULL AND status IN ('PENDING', 'CONFIRMED', 'STARTED') AND trip_ended_at IS NULL);

-- Rows that hang off a booking or package carry its owner, filled here so no insert in the app
-- can forget it (and so row-level security, V28, can see whose they are).
CREATE FUNCTION public.nj_owner_from_booking() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    SELECT b.owner_id INTO NEW.owner_id FROM public.travel_bookings b WHERE b.id = NEW.booking_id;
    RETURN NEW;
END $$;

CREATE FUNCTION public.nj_owner_from_package() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    SELECT p.owner_id INTO NEW.owner_id FROM public.travel_packages p WHERE p.id = NEW.package_id;
    RETURN NEW;
END $$;

CREATE TRIGGER payments_owner BEFORE INSERT ON public.payments
    FOR EACH ROW EXECUTE FUNCTION public.nj_owner_from_booking();
CREATE TRIGGER reviews_owner BEFORE INSERT ON public.reviews
    FOR EACH ROW EXECUTE FUNCTION public.nj_owner_from_booking();
CREATE TRIGGER trip_driver_photos_owner BEFORE INSERT ON public.trip_driver_photos
    FOR EACH ROW EXECUTE FUNCTION public.nj_owner_from_booking();
CREATE TRIGGER package_bookings_owner BEFORE INSERT ON public.package_bookings
    FOR EACH ROW EXECUTE FUNCTION public.nj_owner_from_package();
