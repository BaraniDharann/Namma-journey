-- Every travels owner runs their own Trip fleet: cars (vehicles), drivers, per-category prices
-- and an assignment mode. City rides stay with the platform and independent drivers only.
--
-- The existing fleet, its Trips, packages and owner notifications become owner NJO-0001's. Each
-- fleet driver's car becomes a vehicle record (category guessed from seats), and owner-fleet
-- drivers stop taking City rides. A fresh database has no owner, so every backfill is a no-op.

CREATE TABLE public.vehicles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    category character varying(20) NOT NULL
        CONSTRAINT vehicles_category_check CHECK (category IN ('HATCHBACK', 'SEDAN', 'SUV', 'TEMPO_TRAVELLER')),
    registration_number character varying(20) NOT NULL,
    model character varying(60),
    seats integer NOT NULL CONSTRAINT vehicles_seats_check CHECK (seats BETWEEN 1 AND 30),
    ac boolean NOT NULL DEFAULT true,
    rc_photo character varying(1000),
    active boolean NOT NULL DEFAULT true,
    created_at timestamp(6) without time zone NOT NULL DEFAULT now()
);
-- Same key as the drivers' plate index (V16): upper case, no spaces.
CREATE UNIQUE INDEX uq_vehicles_registration ON public.vehicles (upper(replace(registration_number, ' ', '')));
CREATE INDEX idx_vehicles_owner ON public.vehicles (owner_id);

CREATE TABLE public.owner_trip_rates (
    owner_id bigint NOT NULL REFERENCES public.owners (id),
    category character varying(20) NOT NULL
        CONSTRAINT owner_trip_rates_category_check CHECK (category IN ('HATCHBACK', 'SEDAN', 'SUV', 'TEMPO_TRAVELLER')),
    per_km numeric(10, 2) NOT NULL CONSTRAINT owner_trip_rates_per_km_check CHECK (per_km > 0),
    per_hour numeric(10, 2) NOT NULL CONSTRAINT owner_trip_rates_per_hour_check CHECK (per_hour > 0),
    updated_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (owner_id, category)
);

-- The owner's free licence (Sarathi) and RC (Vahan / mParivahan) checks before approving a driver.
CREATE TABLE public.driver_verification_checks (
    driver_id bigint NOT NULL REFERENCES public.drivers (id) ON DELETE CASCADE,
    type character varying(16) NOT NULL CONSTRAINT driver_checks_type_check CHECK (type IN ('LICENCE', 'RC')),
    result character varying(16) NOT NULL CONSTRAINT driver_checks_result_check CHECK (result IN ('VERIFIED', 'FAILED')),
    note character varying(500),
    checked_by_owner_id bigint REFERENCES public.owners (id),
    checked_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (driver_id, type)
);

-- NJO-0001 keeps today's automatic assignment (set below); everyone else starts on manual.
ALTER TABLE public.owners
    ADD COLUMN assignment_mode character varying(8) NOT NULL DEFAULT 'MANUAL'
        CONSTRAINT owners_assignment_mode_check CHECK (assignment_mode IN ('AUTO', 'MANUAL'));

ALTER TABLE public.drivers
    ADD COLUMN owner_id bigint REFERENCES public.owners (id),
    ADD COLUMN default_vehicle_id bigint REFERENCES public.vehicles (id) ON DELETE SET NULL;
CREATE INDEX idx_drivers_owner ON public.drivers (owner_id);

ALTER TABLE public.travel_bookings
    ADD COLUMN owner_id bigint REFERENCES public.owners (id),
    ADD COLUMN car_category character varying(20)
        CONSTRAINT travel_bookings_car_category_check CHECK (car_category IN ('HATCHBACK', 'SEDAN', 'SUV', 'TEMPO_TRAVELLER')),
    ADD COLUMN vehicle_id bigint REFERENCES public.vehicles (id);
CREATE INDEX idx_travel_bookings_owner ON public.travel_bookings (owner_id, booking_date DESC);

ALTER TABLE public.travel_packages ADD COLUMN owner_id bigint REFERENCES public.owners (id);
ALTER TABLE public.payments ADD COLUMN owner_id bigint;
ALTER TABLE public.reviews ADD COLUMN owner_id bigint;
ALTER TABLE public.trip_driver_photos ADD COLUMN owner_id bigint;
ALTER TABLE public.package_bookings ADD COLUMN owner_id bigint;
CREATE INDEX idx_payments_owner ON public.payments (owner_id);
CREATE INDEX idx_reviews_owner ON public.reviews (owner_id);
CREATE INDEX idx_package_bookings_owner ON public.package_bookings (owner_id);

-- ---------------------------------------------------------------------------------------------
-- Moving the existing data to NJO-0001
-- ---------------------------------------------------------------------------------------------

UPDATE public.owners SET assignment_mode = 'AUTO' WHERE owner_code = 'NJO-0001';

UPDATE public.drivers d SET owner_id = o.id
FROM public.owners o
WHERE o.owner_code = 'NJO-0001' AND d.fleet = 'OWNER_FLEET';

-- Each fleet driver's car becomes a vehicle; plates are already unique among drivers (V16).
INSERT INTO public.vehicles (owner_id, category, registration_number, model, seats, ac)
SELECT d.owner_id,
       CASE WHEN d.vehicle_seats <= 5 THEN 'SEDAN' WHEN d.vehicle_seats <= 8 THEN 'SUV' ELSE 'TEMPO_TRAVELLER' END,
       COALESCE(NULLIF(upper(replace(d.vehicle_number, ' ', '')), ''), 'TEMP-' || d.id),
       d.vehicle_model, LEAST(GREATEST(d.vehicle_seats, 1), 30), d.vehicle_ac
FROM public.drivers d
WHERE d.fleet = 'OWNER_FLEET' AND d.owner_id IS NOT NULL
ORDER BY d.id;

UPDATE public.drivers d SET default_vehicle_id = v.id
FROM public.vehicles v
WHERE d.fleet = 'OWNER_FLEET'
  AND v.registration_number = COALESCE(NULLIF(upper(replace(d.vehicle_number, ' ', '')), ''), 'TEMP-' || d.id);

-- Owner-fleet drivers take Trips only.
UPDATE public.drivers SET serves_city = false WHERE fleet = 'OWNER_FLEET';

UPDATE public.travel_bookings b SET owner_id = o.id
FROM public.owners o
WHERE o.owner_code = 'NJO-0001' AND b.service_mode = 'TRIP';

UPDATE public.travel_bookings b SET vehicle_id = d.default_vehicle_id, car_category = v.category
FROM public.drivers d JOIN public.vehicles v ON v.id = d.default_vehicle_id
WHERE b.service_mode = 'TRIP' AND b.driver_id = d.id;

UPDATE public.travel_bookings SET car_category = 'SEDAN' WHERE service_mode = 'TRIP' AND car_category IS NULL;

UPDATE public.payments p SET owner_id = b.owner_id FROM public.travel_bookings b WHERE b.id = p.booking_id;
UPDATE public.reviews r SET owner_id = b.owner_id FROM public.travel_bookings b WHERE b.id = r.booking_id;
UPDATE public.trip_driver_photos t SET owner_id = b.owner_id FROM public.travel_bookings b WHERE b.id = t.booking_id;

UPDATE public.travel_packages p SET owner_id = o.id FROM public.owners o WHERE o.owner_code = 'NJO-0001';
UPDATE public.package_bookings pb SET owner_id = p.owner_id FROM public.travel_packages p WHERE p.id = pb.package_id;

UPDATE public.notifications n SET recipient_id = o.id::text
FROM public.owners o
WHERE o.owner_code = 'NJO-0001' AND n.recipient_id = 'owner' AND n.recipient_role = 'ROLE_OWNER';

-- NJO-0001's prices for every category start from today's single price.
INSERT INTO public.owner_trip_rates (owner_id, category, per_km, per_hour)
SELECT o.id, c.category,
       COALESCE((SELECT price_per_km FROM public.pricing_config ORDER BY updated_at DESC LIMIT 1), 10.00),
       COALESCE((SELECT price_per_hour FROM public.pricing_config ORDER BY updated_at DESC LIMIT 1), 150.00)
FROM public.owners o
CROSS JOIN (VALUES ('HATCHBACK'), ('SEDAN'), ('SUV'), ('TEMPO_TRAVELLER')) AS c (category)
WHERE o.owner_code = 'NJO-0001';

